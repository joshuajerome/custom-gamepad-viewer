/* Standalone (offline) overlay builder.

Produces one self-contained HTML file for Streamlabs/OBS "Local file" sources,
which load over file:// (no ES modules, no fetch, no query string). Everything
is inlined: CSS, the bundled overlay script, the settings query and the theme's
CSS variables with images as data: URIs. overlay.js reads the baked config from
window.CGV_STANDALONE instead of the URL and the network.
*/

import { bundleModules, collectSources } from './bundle.js';
import { resolveThemeVars } from './themes.js';

const OVERLAY_ENTRY = 'js/overlay.js';

/** Make text safe to embed inside a <script> or <style> element. */
function escapeForTag(text, tag) {
  return String(text).replace(new RegExp(`</(${tag})`, 'gi'), '<\\/$1');
}

/** Assemble the standalone document from already-resolved parts. Pure. */
export function standaloneHtml({ title, css, script, config }) {
  const json = JSON.stringify(config).replace(/</g, '\\u003c');
  return `<!doctype html>
<!-- Custom Gamepad Viewer standalone overlay. Generated by the builder; settings are baked in. -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${title.replace(/[<>&"]/g, '')}</title>
<style>
${escapeForTag(css, 'style')}
</style>
</head>
<body>
<div id="stage"></div>
<pre id="debug" hidden></pre>
<script>window.CGV_STANDALONE = ${json};</script>
<script>
${escapeForTag(script, 'script')}
</script>
</body>
</html>
`;
}

async function toDataUri(url, fetchFn) {
  const res = await fetchFn(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const type = res.headers.get('content-type') || 'application/octet-stream';
  const bytes = new Uint8Array(await res.arrayBuffer());
  let binary = '';
  for (let i = 0; i < bytes.length; i += 0x8000) {
    binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  }
  return `data:${type.split(';')[0]};base64,${btoa(binary)}`;
}

/** Replace every url("http(s)://...") in the theme variables with a data: URI. */
async function inlineVarUrls(vars, fetchFn) {
  const out = {};
  for (const [name, value] of Object.entries(vars)) {
    const m = /^url\("(https?:[^"]+)"\)$/.exec(value);
    out[name] = m ? `url("${await toDataUri(m[1], fetchFn)}")` : value;
  }
  return out;
}

/**
 * Build the standalone overlay for `settings` (as produced by parseSettings).
 * `query` is the overlay query string those settings serialize to.
 */
export async function buildStandalone({ layout, settings, query, siteUrl, fetchFn = fetch }) {
  const text = async (path) => {
    const res = await fetchFn(new URL(path, siteUrl), { cache: 'no-cache' });
    if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
    return res.text();
  };

  const sources = await collectSources(OVERLAY_ENTRY, siteUrl, fetchFn);
  const script = bundleModules(OVERLAY_ENTRY, sources);
  const css = `${await text('css/overlay.css')}\n${await text(layout.cssHref)}`;
  const themesUrl = new URL('themes/', siteUrl).href;
  const vars = await inlineVarUrls(
    await resolveThemeVars(layout, themesUrl, settings.theme, settings.colors, fetchFn), fetchFn);

  return standaloneHtml({
    title: `Gamepad Overlay (${settings.theme}, P${settings.player})`,
    css,
    script,
    config: { query, vars },
  });
}
